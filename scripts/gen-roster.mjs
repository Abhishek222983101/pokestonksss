#!/usr/bin/env node
// Generates crates/duel-rules/src/roster_data.rs and packages/rules-wasm/src/roster-data.ts from rules/roster.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const roster = JSON.parse(readFileSync(resolve(root, 'rules/roster.json'), 'utf8'));
const T = roster.types;
const K = { strike: 0, guard: 1, charge: 2 };
const tIdx = (n) => { const i = T.indexOf(n); if (i < 0) throw new Error('bad type ' + n); return i; };

if (roster.champions.length !== 8) throw new Error('need 8 champions');
roster.champions.forEach((c, i) => {
  if (c.id !== i) throw new Error('ids must be 0..7 in order');
  if (c.moves.length !== 4) throw new Error('4 moves');
  const [a, b, g, ch] = c.moves;
  if (a.kind !== 'strike' || a.type !== c.type) throw new Error(c.name + ': slot0 must be own-type strike');
  if (b.kind !== 'strike' || b.type === c.type) throw new Error(c.name + ': slot1 must be other-type strike');
  if (g.kind !== 'guard' || ch.kind !== 'charge') throw new Error(c.name + ': slots 2/3');
  if (c.palette.length !== 3) throw new Error('palette');
});
if (new Set(roster.champions.map((c) => c.type)).size !== 5) throw new Error('roster must cover every type');

const mv = (c, m) => {
  if (m.kind === 'strike') return `Move { kind: MoveKind::Strike, typ: ${tIdx(m.type)}, power: ${m.power}, acc: ${m.acc} }`;
  return `Move { kind: MoveKind::${m.kind === 'guard' ? 'Guard' : 'Charge'}, typ: ${tIdx(c.type)}, power: 0, acc: 100 }`;
};
let rs = `// @generated by scripts/gen-roster.mjs from rules/roster.json. DO NOT EDIT.\nuse crate::{Move, MoveKind, Species};\n\n`;
rs += `pub const ROSTER_LEN: usize = ${roster.champions.length};\n\n`;
rs += `pub const NAMES: [&str; ROSTER_LEN] = [${roster.champions.map((c) => JSON.stringify(c.name)).join(', ')}];\n\n`;
rs += `pub const ROSTER: [Species; ROSTER_LEN] = [\n`;
for (const c of roster.champions) {
  rs += `    Species {\n        id: ${c.id}, typ: ${tIdx(c.type)}, hp: ${c.hp}, atk: ${c.atk}, def: ${c.def}, spd: ${c.spd}, feed: ${c.feed},\n        moves: [\n`;
  for (const m of c.moves) rs += `            ${mv(c, m)},\n`;
  rs += `        ],\n    },\n`;
}
rs += `];\n`;
writeFileSync(resolve(root, 'crates/duel-rules/src/roster_data.rs'), rs);

const ts = `// @generated by scripts/gen-roster.mjs from rules/roster.json. DO NOT EDIT.\nexport const ROSTER_DATA = ${JSON.stringify(roster, null, 2)} as const;\n`;
mkdirSync(resolve(root, 'packages/rules-wasm/src'), { recursive: true });
writeFileSync(resolve(root, 'packages/rules-wasm/src/roster-data.ts'), ts);
console.log('roster generated');
